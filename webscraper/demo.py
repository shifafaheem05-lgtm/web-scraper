"""Build the public demo page (docs/index.html) from a file you scraped.

    webscraper scrape --all-pages --details -o output/books.csv
    webscraper demo output/books.csv -o docs/index.html
"""
from __future__ import annotations

import html
from datetime import date
from importlib import resources
from typing import Sequence

from .models import Book
from .report import _bars
from .stats import summarize

DESCRIPTION = ("Interactive report from a Python web scraper: crawls product catalogues, visits detail pages in "
               "parallel, caches pages and exports CSV, JSON, SQLite, Excel and HTML.")


def build_demo_page(books: Sequence[Book], real: bool = True, source_url: str = "https://books.toscrape.com") -> str:
    """Return the full HTML of the demo page.

    real=True  -> the banner says the data was scraped from the live site, today.
    real=False -> the banner says the data is generated sample data (never pass sample data off as real).
    """
    esc = html.escape
    stats = summarize(books)
    if not stats.get("count"):
        raise ValueError("no books to show; scrape something first")
    has_cats = bool(stats.get("by_category"))

    tiles = [("books scraped", stats["count"]), ("average price", f'£{stats["average_price"]:.2f}'),
             ("median price", f'£{stats["median_price"]:.2f}'), ("in stock", stats["in_stock"])]
    if has_cats:
        tiles.append(("categories", len(stats["by_category"])))
    tiles_html = "".join(f'<div class="tile"><b>{esc(str(v))}</b><span>{esc(k)}</span></div>' for k, v in tiles)

    def cell(value: object, numeric: bool = False, cls: str = "", data: object = None) -> str:
        text = "" if value is None else str(value)
        shown = esc(text)
        key = esc(str(data) if data is not None else (text if numeric else text.lower()))
        return f'<td{f" class={cls}" if cls else ""} data-v="{key}">{shown}</td>'

    rows = "".join(
        "<tr>" + cell(b.title, cls="t") + cell(b.category) + cell(f"{b.price:.2f}", True)
        + cell("★" * b.rating + "☆" * (5 - b.rating), data=b.rating) + cell("yes" if b.in_stock else "no")
        + cell(b.stock_quantity, True) + cell(b.num_reviews, True) + cell(b.upc) + "</tr>" for b in books)
    heads = "".join(f'<th data-n="{n}" scope="col">{h}</th>' for h, n in (
        ("Title", 0), ("Category", 0), ("Price £", 1), ("Rating", 1), ("In stock", 0), ("Stock", 1), ("Reviews", 1), ("UPC", 0)))

    if real:
        eyebrow = "Live demo · real scrape"
        notice = (f'<p class="notice"><b>Real data.</b> Scraped from <a href="{esc(source_url)}" target="_blank" rel="noopener">'
                  f"{esc(source_url.replace('https://', ''))}</a> on {date.today():%d %B %Y}. That website is a practice site built "
                  "for scraping, so its books and prices are fictional.</p>")
        intro = ('<p class="lead" style="margin-bottom:14px">This page was generated by the scraper itself with '
                 '<code>webscraper demo</code>, from the file it exported.</p>')
    else:
        eyebrow = "Live demo · sample data"
        notice = ("<p class=\"notice\"><b>Sample data.</b> These books were generated by the project's test site, which copies "
                  "the page structure of books.toscrape.com. They are not real listings. Run the commands at the bottom to get "
                  "real results.</p>")
        intro = '<p class="lead" style="margin-bottom:14px">Generated sample data, shown the way the real report looks.</p>'

    cats_panel = cat_select = ""
    if has_cats:
        cats = _bars([(k, v["count"]) for k, v in list(stats["by_category"].items())[:10]])
        cats_panel = f'<div class="panel"><h3>Books per category</h3>{cats}</div>'
        opts = "".join(f"<option>{esc(c)}</option>" for c in sorted(stats["by_category"]))
        cat_select = f'<select id="cat" aria-label="Filter by category"><option value="">All categories</option>{opts}</select>'

    template = resources.files("webscraper").joinpath("templates/demo.html").read_text(encoding="utf-8")
    page = (template.replace("{{META_DESC}}", esc(DESCRIPTION, quote=True)).replace("{{EYEBROW}}", eyebrow)
            .replace("{{NOTICE}}", notice).replace("{{INTRO}}", intro).replace("{{COUNT}}", str(len(books)))
            .replace("{{TILES}}", tiles_html)
            .replace("{{RATINGS}}", _bars([(f"{r} star", n) for r, n in stats["by_rating"].items()]))
            .replace("{{PRICES}}", _bars(stats["price_buckets"])).replace("{{CATS_PANEL}}", cats_panel)
            .replace("{{CAT_SELECT}}", cat_select).replace("{{HEADS}}", heads).replace("{{ROWS}}", rows))
    return (f'<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            f'<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            f'{page.split("<main>", 1)[0]}</head>\n<body>\n<main>{page.split("<main>", 1)[1]}\n</body>\n</html>\n')
